// Each filled cell becomes a 1x1 rect; consecutive cells in a row merge into one.
export function spriteRects(rows: string[], eyesClosed: boolean) {
  const rects: { x: number; y: number; w: number }[] = [];
  rows.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x++) {
      const c = row[x];
      const filled = c === "#" || (c === "o" && eyesClosed);
      if (filled && start < 0) start = x;
      if (!filled && start >= 0) {
        rects.push({ x: start, y, w: x - start });
        start = -1;
      }
    }
  });
  return rects;
}
